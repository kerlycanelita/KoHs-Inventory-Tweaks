def sdl_button(number: str) -> str:
    """A literal GLFW mouse button as 26.3 numbers it: SDL counts from 1 and puts the right button third."""
    names = {"0": "MOUSE_BUTTON_LEFT", "1": "MOUSE_BUTTON_RIGHT", "2": "MOUSE_BUTTON_MIDDLE"}
    return "com.mojang.blaze3d.platform.InputConstants." + names[number] if number in names else str(int(number) + 1)



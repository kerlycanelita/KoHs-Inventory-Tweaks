RULES_1_21_11 = [(re.compile(rf"\b{old}\b"), new) for old, new in RENAMES_1_21_11.items()]
RULES_1_21_11 += [(re.compile(rf"\bgraphics\.{old}\("), f"graphics.{new}(") for old, new in DRAW_CALLS_1_21_11.items()]
RULES_1_21_11 += [
    (re.compile(r"import net\.minecraft\.util\.LightTexture;"), "import net.minecraft.client.renderer.LightTexture;"),
    (re.compile(r"net/minecraft/client/renderer/state/gui/pip/"), "net/minecraft/client/gui/render/state/pip/"),
    (re.compile(r"net\.minecraft\.client\.renderer\.state\.gui\.pip\."), "net.minecraft.client.gui.render.state.pip."),
    (re.compile(r"\.containerInput\(\)"), ".clickType()"),
    (re.compile(r"\.resizeGui\(\)"), ".resizeDisplay()"),
]


def port_tree(version: str) -> None:
    target = REPO / f"versions/kohs-inventory-tweaks-{version}"
    mixins = target / PKG / "mixin"
    kept = {name: (target / PKG / name).read_bytes() for name in KEEP.get(version, ())}
    for part in ("src/client", "src/main"):
        shutil.rmtree(target / part)
        shutil.copytree(REPO / part, target / part)
    for name, data in kept.items():
        (target / PKG / name).write_bytes(data)
    kept = {Path(name).name for name in kept}
    edit(target / "src/main/resources/fabric.mod.json", [('"minecraft": "26.1.2"', f'"minecraft": "{version}"')])
    mixin_config = target / "src/main/resources/kohs_inventory_tweaks.client.mixins.json"

    if version == "26.2":
        # Verified against the 26.2 client jar: Minecraft#setScreen moved to Gui, the
        # HUD from Gui to Hud, AbstractContainerScreen lost its snapback extraction,
        # and the picture-in-picture states changed constructor types (no sign state).
        (mixins / "MinecraftScreenMixin.java").unlink()
        (mixins / "GuiMixin.java").unlink()
        edit(mixin_config, [
            ('    "MinecraftScreenMixin",\n', '    "GuiScreenMixin",\n'),
            ('    "GuiMixin",\n', '    "HudMixin",\n'),
        ])
        container = mixins / "AbstractContainerScreenMixin.java"
        remove_member(container, '\t@Inject(method = "extractSnapbackItem"')
        edit(container, [
            ("import dev.zymekoh.kohsinventorytweaks.render.InventoryAnimationController;\n", ""),
            ("@Mixin(AbstractContainerScreen.class)\n",
             "/** 26.2 has no snapback extraction, so there is no item-return motion to reduce here. */\n"
             "@Mixin(AbstractContainerScreen.class)\n"),
        ])
        scene = mixins / "ContainerSceneMixin.java"
        edit(scene, [
            ("GuiSkinRenderState;<init>(Lnet/minecraft/client/model/player/PlayerModel;",
             "GuiSkinRenderState;<init>(Lnet/minecraft/client/model/Model$Simple;"),
            ("GuiEntityRenderState;<init>(Lnet/minecraft/client/renderer/entity/state/EntityRenderState;Lorg/joml/Vector3f;Lorg/joml/Quaternionf;Lorg/joml/Quaternionf;",
             "GuiEntityRenderState;<init>(Lnet/minecraft/client/renderer/entity/state/EntityRenderState;Lorg/joml/Vector3fc;Lorg/joml/Quaternionfc;Lorg/joml/Quaternionfc;"),
        ])
        remove_member(scene, '\t@ModifyArgs(method = "sign"')
        changed = apply_rules(sources(target / PKG, kept), RULES_26_2)
    elif version == "1.21.11":
        # Verified against the 1.21.11 client jar and Fabric API 0.141.6. The complete
        # GLFW poll ends in Window#updateDisplay (Minecraft#run has no pollEvents), there
        # is no Window#isFocused or Camera#getFov, handleKeybinds drains no HUD toggle
        # before the inventory, the container background is drawn in renderBg, and the
        # picture-in-picture states live in gui.render.state.pip, built by GuiGraphics'
        # submit*RenderState.
        (mixins / "MinecraftInputPollMixin.java").unlink()
        edit(mixin_config, [
            ('"compatibilityLevel": "JAVA_25"', '"compatibilityLevel": "JAVA_21"'),
            ('    "MinecraftInputPollMixin",\n', '    "WindowMixin",\n'),
        ])
        edit(target / "src/main/resources/fabric.mod.json", [('"java": ">=25"', '"java": ">=21"')])
        edit(target / PKG / "inventory/SuperFastInventoryController.java", [
            ("!minecraft.isWindowActive() || !minecraft.getWindow().isFocused() || ", "!minecraft.isWindowActive() || "),
        ])
        edit(target / PKG / "cursor/CursorLandingController.java", [
            ("\n\t\t\t&& minecraft.getWindow().isFocused() && !minecraft.getWindow().isMinimized();",
             "\n\t\t\t&& !minecraft.getWindow().isMinimized();"),
        ])
        edit(target / PKG / "KoHsInventoryTweaksClient.java", [
            (".registerReloadListener(", ".registerReloader("),
            ("import net.fabricmc.fabric.api.client.rendering.v1.LivingEntityRenderLayerRegistrationCallback;",
             "import net.fabricmc.fabric.api.client.rendering.v1.LivingEntityFeatureRendererRegistrationCallback;"),
            ("LivingEntityRenderLayerRegistrationCallback.EVENT", "LivingEntityFeatureRendererRegistrationCallback.EVENT"),
        ])
        edit(target / PKG / "input/ConfigMenuKeyBinding.java", [
            ("import net.fabricmc.fabric.api.client.keymapping.v1.KeyMappingHelper;",
             "import net.fabricmc.fabric.api.client.keybinding.v1.KeyBindingHelper;"),
            ("KeyMappingHelper.registerKeyMapping(", "KeyBindingHelper.registerKeyBinding("),
        ])
        for name in ("render/VisiblePlayerBackdropController.java", "render/VisiblePlayerGlowController.java"):
            edit(target / PKG / name, [
                ("Math.max(20.0F, camera.getFov())", "Math.max(20.0, minecraft.options.fov().get())"),
            ])
        edit(mixins / "ContainerSceneMixin.java", [
            ('@ModifyArgs(method = "skin"', '@ModifyArgs(method = "submitSkinRenderState"'),
            ('@ModifyArgs(method = "entity"', '@ModifyArgs(method = "submitEntityRenderState"'),
            ('@ModifyArgs(method = "book"', '@ModifyArgs(method = "submitBookModelRenderState"'),
            ('@ModifyArgs(method = "bannerPattern"', '@ModifyArgs(method = "submitBannerPatternRenderState"'),
            ('@ModifyArgs(method = "sign"', '@ModifyArgs(method = "submitSignRenderState"'),
        ])
        edit(mixins / "ContainerScreenMixin.java", [('method = "extractBackground",', 'method = "renderBg",')])
        edit(mixins / "InventoryScreenMixin.java", [
            ('method = "extractBackground(Lnet/minecraft/client/gui/GuiGraphicsExtractor;IIF)V",', 'method = "renderBg",'),
        ])
        edit(target / PKG / "compat/CompatibilityIssueManager.java", [
            ('"net.minecraft.client.gui.screens.inventory.InventoryScreen#extractBackground -> "',
             '"net.minecraft.client.gui.screens.inventory.InventoryScreen#renderBg -> "'),
        ])
        changed = apply_rules(sources(target / PKG, kept), RULES_1_21_11)
    else:
        changed = 0
    print(f"tree {version}: rebuilt from 26.1.2, {changed} files translated")


def port_debug(version: str) -> None:
    source = REPO / "debug/kohs-inventory-debug-26.1.2"
    target = REPO / f"debug/kohs-inventory-debug-{version}"
    mixins = target / DEBUG_PKG / "mixin"
    kept = {name: (mixins / name).read_bytes() for name in DEBUG_KEEP.get(version, ())}
    for part in ("src/client", "src/main"):
        shutil.rmtree(target / part)
        shutil.copytree(source / part, target / part)
    for name, data in kept.items():
        (mixins / name).write_bytes(data)
    if version in ("26.1", "26.1.1"):
        print(f"debug {version}: rebuilt from the 26.1.2 companion; labs compile from tools/qa")
        return

    qa = target / "src/qa"
    if qa.exists():
        shutil.rmtree(qa)
    for lab in LABS:
        (qa / lab).mkdir(parents=True)
        for java in (REPO / "tools/qa" / lab).glob("*.java"):
            shutil.copy(java, qa / lab / java.name)
    java_files = [path for path in list((target / "src/client/java").rglob("*.java")) + list(qa.rglob("*.java"))
                  if path.name not in kept]
    config = target / "src/client/resources/kohs-inventory-debug.client.mixins.json"

    if version == "26.2":
        # Screen ownership moved to Gui: the lifecycle hooks follow it into GuiTraceMixin.
        remove_member(mixins / "MinecraftTraceMixin.java", '\t@Inject(method = "setScreen", at = @At("HEAD"))')
        remove_member(mixins / "MinecraftTraceMixin.java", '\t@Inject(method = "setScreen", at = @At("RETURN"))')
        edit(mixins / "MinecraftTraceMixin.java", [
            ("import net.minecraft.client.gui.screens.Screen;\n", ""),
            ("import org.jspecify.annotations.Nullable;\n", ""),
        ])
        trace, crlf = read(mixins / "GuiTraceMixin.java")
        if "RecordingOverlay.opened()" not in trace:
            edit(mixins / "GuiTraceMixin.java", [
                ("\t\tDebugCollector.onSetScreen(Minecraft.getInstance(), screen, true);\n",
                 "\t\tDebugCollector.onSetScreen(Minecraft.getInstance(), screen, true);\n"
                 "\t\tif (screen instanceof net.minecraft.client.gui.screens.inventory.InventoryScreen) {\n"
                 "\t\t\tdev.zymekoh.kohsinventorydebug.RecordingOverlay.opened();\n"
                 "\t\t}\n"),
            ])
        edit(config, [('    "InventoryScreenInitProbeMixin",\n', '    "GuiTraceMixin",\n    "InventoryScreenInitProbeMixin",\n')])
        changed = apply_rules(java_files, RULES_26_2)
    else:
        edit(config, [('"compatibilityLevel": "JAVA_25"', '"compatibilityLevel": "JAVA_21"')])
        edit(target / "src/main/resources/fabric.mod.json", [('"java": ">=25"', '"java": ">=21"')])
        edit(target / DEBUG_PKG / "MacroTestController.java", [
            ("!minecraft.isWindowActive() || !minecraft.getWindow().isFocused() || ", "!minecraft.isWindowActive() || "),
        ])
        # 1.21.11 LevelSettings: (name, mode, hardcore, difficulty, commands, rules, data).
        edit(target / DEBUG_PKG / "LabWorld.java", [
            ("\t\t\t\tLevelSettings.DifficultySettings.DEFAULT,\n\t\t\t\ttrue,\n\t\t\t\tWorldDataConfiguration.DEFAULT\n",
             "\t\t\t\tfalse,\n\t\t\t\tnet.minecraft.world.Difficulty.NORMAL,\n\t\t\t\ttrue,\n"
             "\t\t\t\tnew net.minecraft.world.level.gamerules.GameRules(WorldDataConfiguration.DEFAULT.enabledFeatures()),\n"
             "\t\t\t\tWorldDataConfiguration.DEFAULT\n"),
        ])
        changed = apply_rules(java_files, RULES_1_21_11)
    print(f"debug {version}: rebuilt from the 26.1.2 companion, {changed} files translated (labs in src/qa)")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("version", choices=(*TARGETS, "all"))
    parser.add_argument("--tree", action="store_true", help="only the source tree")
    parser.add_argument("--debug", action="store_true", help="only the debug companion")
    arguments = parser.parse_args()
    both = not arguments.tree and not arguments.debug
    for version in TARGETS if arguments.version == "all" else (arguments.version,):
        if both or arguments.tree:
            port_tree(version)
        if both or arguments.debug:
            port_debug(version)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

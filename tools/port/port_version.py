#!/usr/bin/env python3
"""Rebuilds a maintained target from the 26.1.2 root: its source tree and its debug companion.

    python tools/port/port_version.py 26.2            # tree and companion
    python tools/port/port_version.py 1.21.11 --tree  # only versions/kohs-inventory-tweaks-1.21.11
    python tools/port/port_version.py all

Features are written once, in the root tree. Every other target is the root with its
version's API differences applied, and those differences live here, each one checked
against that version's client jar. After a port, build the target and run
`python tools/verify-all-versions.py`; a mixin whose target moved again shows up
there before the game ever starts.

The rebuild replaces `src/client` and `src/main` of the target. Files a target needs
that the root cannot produce (its replacement for a mixin whose target moved) are
listed in `KEEP` and carried across. Anything else edited by hand in a target is
lost, which is the point: the root is the only place to edit.

The debug companions follow the 26.1.2 companion. Its labs stay in tools/qa; 26.1
and 26.1.1 compile them from there, while 26.2 and 1.21.11 get a translated copy
under `src/qa`, regenerated by this script.
"""
from __future__ import annotations

import argparse
import re
import shutil
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
PKG = "src/client/java/dev/zymekoh/kohsinventorytweaks"
DEBUG_PKG = "src/client/java/dev/zymekoh/kohsinventorydebug"
LABS = ("cursor-contract", "pvp-input", "showcase")
TARGETS = ("26.1", "26.1.1", "26.2", "1.21.11")

# Files only the target itself can provide, relative to its package root: mixins
# whose target moved, and the key order read from that version's own jar.
KEEP = {
    "26.2": ("mixin/GuiScreenMixin.java", "mixin/HudMixin.java", "inventory/VanillaKeyOrder.java"),
    "1.21.11": ("mixin/WindowMixin.java", "inventory/VanillaKeyOrder.java"),
}
DEBUG_KEEP = {"26.2": ("GuiTraceMixin.java",)}


def read(path: Path) -> tuple[str, bool]:
    raw = path.read_bytes().decode("utf-8")
    return raw.replace("\r\n", "\n"), "\r\n" in raw


def write(path: Path, text: str, crlf: bool) -> None:
    path.write_bytes((text.replace("\n", "\r\n") if crlf else text).encode("utf-8"))


def edit(path: Path, pairs) -> None:
    """Exact replacements that must each match once, so a moved line fails loudly."""
    text, crlf = read(path)
    for old, new in pairs:
        if text.count(old) != 1:
            raise SystemExit(f"{path.relative_to(REPO)}: expected one match for {old[:80]!r}, found {text.count(old)}")
        text = text.replace(old, new)
    write(path, text, crlf)


def remove_member(path: Path, start_marker: str) -> None:
    """Removes one annotated member, from its annotation to its closing brace."""
    text, crlf = read(path)
    start = text.index(start_marker)
    end = text.index("\n\t}\n", start) + len("\n\t}\n")
    head, tail = text[:start], text[end:].lstrip("\n")
    if tail.startswith("}"):
        # It was the last member: no blank line before the class closes.
        head = head.rstrip("\n") + "\n"
    write(path, head + tail, crlf)


def sources(*roots_and_kept) -> list[Path]:
    """Every Java file under the given roots, except the target's own kept files."""
    *roots, kept = roots_and_kept
    return [path for root in roots for path in root.rglob("*.java") if path.name not in kept]


def camel(name: str) -> str:
    head, *rest = name.lower().split("_")
    return head + "".join(part.capitalize() for part in rest)


def apply_rules(files, rules) -> int:
    changed = 0
    for java in files:
        text, crlf = read(java)
        new = text
        for pattern, replacement in rules:
            new = pattern.sub(replacement, new)
        if new != text:
            changed += 1
            write(java, new, crlf)
    return changed


# 26.2 moved screen ownership from Minecraft to Gui and the HUD to Hud. The owner must
# not follow a dot, or package names such as Fabric's client.screen.v1 would match.
OWNER = r"(?<![\w.])(minecraft|this\.minecraft|mc|client|Minecraft\.getInstance\(\))"
RULES_26_2 = [
    (re.compile(OWNER + r"\.setScreen\("), r"\1.gui.setScreen("),
    (re.compile(OWNER + r"\.screen\b(?!\()"), r"\1.gui.screen()"),
    (re.compile(OWNER + r"\.getOverlay\(\)"), r"\1.gui.overlay()"),
    (re.compile(OWNER + r"\.getToastManager\(\)"), r"\1.gui.toastManager()"),
    (re.compile(OWNER + r"\.gui\.getChat\(\)"), r"\1.gui.hud.getChat()"),
    (re.compile(OWNER + r"\.getMainRenderTarget\(\)"), r"\1.gameRenderer.mainRenderTarget()"),
    (re.compile(OWNER + r"\.isSingleplayer\(\)"), r"\1.hasSingleplayerServer()"),
    (re.compile(r"\.getMainCamera\(\)"), ".mainCamera()"),
    # The HUD's hidden flag moved from Options to Hud, behind a toggle.
    (re.compile(r"(\w+)\.options\.hideGui = (\w+);"), r"if (\1.gui.hud.isHidden() != \2) \1.gui.hud.toggle();"),
    (re.compile(r"(\w+)\.options\.hideGui\b"), r"\1.gui.hud.isHidden()"),
    # Entity type constants moved to EntityTypes; EntityType keeps the class itself.
    (re.compile(r"\bEntityType\.([A-Z][A-Z0-9_]+)\b"), r"EntityTypes.\1"),
    (re.compile(r"^import net\.minecraft\.world\.entity\.EntityType;$", re.M),
     "import net.minecraft.world.entity.EntityType;\nimport net.minecraft.world.entity.EntityTypes;"),
    # Coloured items became ColorCollections: Items.PURPLE_DYE is Items.DYE.purple().
    (re.compile(r"\bItems\.([A-Z_]+?)_(DYE|SHULKER_BOX)\b"),
     lambda m: f"Items.{'DYE' if m.group(2) == 'DYE' else 'DYED_SHULKER_BOX'}.{camel(m.group(1))}()"),
]


def read(path: Path) -> tuple[str, bool]:
    raw = path.read_bytes().decode("utf-8")
    return raw.replace("\r\n", "\n"), "\r\n" in raw


def write(path: Path, text: str, crlf: bool) -> None:
    path.write_bytes((text.replace("\n", "\r\n") if crlf else text).encode("utf-8"))


def edit(path: Path, pairs) -> None:
    """Exact replacements that must each match once, so a moved line fails loudly."""
    text, crlf = read(path)
    for old, new in pairs:
        if text.count(old) != 1:
            raise SystemExit(f"{path.relative_to(REPO)}: expected one match for {old[:80]!r}, found {text.count(old)}")
        text = text.replace(old, new)
    write(path, text, crlf)


def regex_edit(path: Path, pattern: str, replacement: str) -> None:
    """One regular-expression replacement that must match once, for blocks too long to quote."""
    text, crlf = read(path)
    new, count = re.subn(pattern, replacement, text, flags=re.S)
    if count != 1:
        raise SystemExit(f"{path.relative_to(REPO)}: expected one match for {pattern[:80]!r}, found {count}")
    write(path, new, crlf)


def remove_member(path: Path, start_marker: str) -> None:
    """Removes one annotated member, from its annotation to its closing brace."""
    text, crlf = read(path)
    start = text.index(start_marker)
    end = text.index("\n\t}\n", start) + len("\n\t}\n")
    head, tail = text[:start], text[end:].lstrip("\n")
    if tail.startswith("}"):
        # It was the last member: no blank line before the class closes.
        head = head.rstrip("\n") + "\n"
    write(path, head + tail, crlf)


def sources(*roots_and_kept) -> list[Path]:
    """Every Java file under the given roots, except the target's own kept files."""
    *roots, kept = roots_and_kept
    return [path for root in roots for path in root.rglob("*.java") if path.name not in kept]


def camel(name: str) -> str:
    head, *rest = name.lower().split("_")
    return head + "".join(part.capitalize() for part in rest)


def apply_rules(files, rules) -> int:
    changed = 0
    for java in files:
        text, crlf = read(java)
        new = text
        for pattern, replacement in rules:
            new = pattern.sub(replacement, new)
        if new != text:
            changed += 1
            write(java, new, crlf)
    return changed


